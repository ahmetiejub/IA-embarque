/**
  * @brief ETH MSP Initialization
  * This function configures the hardware resources used in this example
  * @param heth: ETH handle pointer
  * @retval None
  */
void HAL_ETH_MspInit(ETH_HandleTypeDef* heth)
{
  GPIO_InitTypeDef GPIO_InitStruct = {0};
  RCC_PeriphCLKInitTypeDef PeriphClkInitStruct = {0};
  if(heth->Instance==ETH1)
  {
    /* USER CODE BEGIN ETH1_MspInit 0 */
    /* CORRECTION RIF : le DMA de l'Ethernet est un "maitre" de bus. Par defaut il
       n'a pas le droit d'acceder a la RAM securisee (0x34xxxxxx) ou sont les
       descripteurs et les buffers -> aucun paquet n'est emis ni recu (pas de DHCP).
       On lui donne les attributs Secure + Privileged, CID 1, comme le fait
       SystemIsolation_Config() dans les exemples ST (HAL_RIF_RIMC_ConfigMasterAttributes). */
    {
      __HAL_RCC_RIFSC_CLK_ENABLE();

      uint32_t attr = RIFSC->RIMC_ATTRx[6];                   /* 6 = RIF_MASTER_INDEX_ETH1 */
      attr &= ~(RIFSC_RIMC_ATTRx_MCID | RIFSC_RIMC_ATTRx_MSEC | RIFSC_RIMC_ATTRx_MPRIV);
      attr |= (1UL << RIFSC_RIMC_ATTRx_MCID_Pos)              /* CID 1 */
            | RIFSC_RIMC_ATTRx_MSEC                           /* acces secure */
            | RIFSC_RIMC_ATTRx_MPRIV;                         /* acces privilegie */
      RIFSC->RIMC_ATTRx[6] = attr;

      /* Registres de l'ETH1 en secure + privileged (RIF_RISC_PERIPH_INDEX_ETH1 = reg 1, bit 28) */
      RIFSC->RISC_SECCFGRx[1]  |= (1UL << 28);
      RIFSC->RISC_PRIVCFGRx[1] |= (1UL << 28);
    }
    /* USER CODE END ETH1_MspInit 0 */

  /** Initializes the peripherals clock
  */
    PeriphClkInitStruct.PeriphClockSelection = RCC_PERIPHCLK_ETH1;
    PeriphClkInitStruct.Eth1ClockSelection = RCC_ETH1CLKSOURCE_HCLK;

  /* USER CODE BEGIN MACADDRESS */

  /* USER CODE END MACADDRESS */

    if (HAL_RCCEx_PeriphCLKConfig(&PeriphClkInitStruct) != HAL_OK)
    {
      Error_Handler();
    }

    /* Peripheral clock enable */
    __HAL_RCC_ETH1_CLK_ENABLE();

    __HAL_RCC_GPIOD_CLK_ENABLE();
    __HAL_RCC_GPIOF_CLK_ENABLE();
    /**ETH1 GPIO Configuration
    PD1     ------> ETH1_MDC
    PD12     ------> ETH1_MDIO
    PF10     ------> ETH1_RMII_CRS_DV
    PF7     ------> ETH1_RMII_REF_CLK
    PF5     ------> ETH1_CLK
    PF15     ------> ETH1_RMII_RXD1
    PF14     ------> ETH1_RMII_RXD0
    PF11     ------> ETH1_RMII_TX_EN
    PF13     ------> ETH1_RMII_TXD1
    PF12     ------> ETH1_RMII_TXD0
    */
    GPIO_InitStruct.Pin = GPIO_PIN_1|GPIO_PIN_12;
    GPIO_InitStruct.Mode = GPIO_MODE_AF_PP;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
    GPIO_InitStruct.Alternate = GPIO_AF11_ETH1;
    HAL_GPIO_Init(GPIOD, &GPIO_InitStruct);

    GPIO_InitStruct.Pin = GPIO_PIN_10|GPIO_PIN_7|GPIO_PIN_5|GPIO_PIN_15
                          |GPIO_PIN_14|GPIO_PIN_11|GPIO_PIN_13|GPIO_PIN_12;
    GPIO_InitStruct.Mode = GPIO_MODE_AF_PP;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
    GPIO_InitStruct.Alternate = GPIO_AF11_ETH1;
    HAL_GPIO_Init(GPIOF, &GPIO_InitStruct);

    /* USER CODE BEGIN ETH1_MspInit 1 */
    /* CORRECTION : sur la NUCLEO-N657X0-Q, le PHY LAN8742 est relie a
       MDIO = PF4 et MDC = PG11 (cf. exemples ST Nx_*_Echo pour cette carte),
       et non a PD12 / PD1 comme dans le .ioc. On libere PD1/PD12 et on
       configure les bonnes broches. */
    HAL_GPIO_DeInit(GPIOD, GPIO_PIN_1 | GPIO_PIN_12);

    __HAL_RCC_GPIOG_CLK_ENABLE();

    /* Broches RMII + MDIO en vitesse HIGH (horloge RMII a 50 MHz), comme l'exemple ST */
    GPIO_InitStruct.Pin = GPIO_PIN_4                  /* PF4 -> ETH1_MDIO */
                        | GPIO_PIN_5 | GPIO_PIN_7 | GPIO_PIN_10 | GPIO_PIN_11
                        | GPIO_PIN_12 | GPIO_PIN_13 | GPIO_PIN_14 | GPIO_PIN_15;
    GPIO_InitStruct.Mode = GPIO_MODE_AF_PP;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    GPIO_InitStruct.Alternate = GPIO_AF11_ETH1;
    HAL_GPIO_Init(GPIOF, &GPIO_InitStruct);

    GPIO_InitStruct.Pin = GPIO_PIN_11;                /* PG11 -> ETH1_MDC */
    HAL_GPIO_Init(GPIOG, &GPIO_InitStruct);

    /* CORRECTION HORLOGES : les horloges MAC / TX / RX doivent etre actives AVANT
       que HAL_ETH_Init() ecrive la configuration du MAC et des descripteurs DMA
       (juste apres cette fonction). Sinon ces ecritures sont perdues et le
       controleur Ethernet n'emet ni ne recoit rien. (Avant, elles n'etaient
       activees que plus tard, dans NET_Init.) Meme sequence que l'exemple ST. */
    __HAL_RCC_ETH1MAC_CLK_ENABLE();
    __HAL_RCC_ETH1TX_CLK_ENABLE();
    __HAL_RCC_ETH1RX_CLK_ENABLE();
    /* USER CODE END ETH1_MspInit 1 */

  }

}

